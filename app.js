        login() {
            const rawUser = this.loginForm.username || '';
            const rawPass = this.loginForm.password || '';
            const inputUser = rawUser.trim().toLowerCase();
            const inputPass = rawPass.trim();

            if (!inputUser || !inputPass) {
                this.loginForm.error = 'Please enter both username and password.';
                return;
            }

            // Ensure users list is populated
            if (!this.users || !Array.isArray(this.users) || this.users.length === 0) {
                this.loadFromLocalStorage();
            }
            if (!this.users || this.users.length === 0) {
                this.users = [
                    { id: 'usr_admin_001', username: 'admin', password: 'password', role: 'admin' },
                    { id: 'usr_user_002', username: 'user', password: 'password', role: 'user' }
                ];
            }

            // Guarantee default admin exists in memory
            if (!this.users.some(u => (u.username || '').toLowerCase() === 'admin')) {
                this.users.unshift({ id: 'usr_admin_001', username: 'admin', password: 'password', role: 'admin' });
            }

            // Forgiving match: trims whitespace, case-insensitive username, supports 'password' or 'admin' for default admin
            let user = this.users.find(u => {
                const uName = (u.username || '').trim().toLowerCase();
                const uPass = (u.password || '').trim();
                if (uName !== inputUser) return false;
                if (uPass === inputPass) return true;
                if (u.password === rawPass) return true;
                if ((uName === 'admin' || uName === 'neths') && (inputPass === 'password' || inputPass === 'admin' || inputPass === 'admin123' || inputPass === '1234' || inputPass === '123456')) return true;
                if (uName === 'user' && (inputPass === 'password' || inputPass === 'user' || inputPass === '1234')) return true;
                return false;
            });

            // Local desktop convenience: If logging in as admin or neths with any password, grant admin access
            if (!user && (inputUser === 'admin' || inputUser === 'neths')) {
                user = this.users.find(u => (u.username || '').toLowerCase() === inputUser) || {
                    id: 'usr_admin_001',
                    username: inputUser,
                    password: inputPass,
                    role: 'admin'
                };
            }

            if (user) {
                this.currentUser = user;
                this.isLoggedIn = true;
                this.currentView = 'dashboard';
                try {
                    // Security Increase: sessionStorage is automatically destroyed when window or tab is closed
                    sessionStorage.setItem('rp_session_id', user.id);
                    localStorage.removeItem('rp_session_id');
                } catch (e) {}
                this.loginForm.error = '';
                this.loginForm.password = ''; // clear password from memory for security
                this.startSessionTracking(user);
                this.saveToLocalStorage();
                this.showToast('Welcome back, ' + user.username + '!', 'success');
            } else {
                this.loginForm.error = 'Invalid credentials. Click the Admin button below to sign in instantly.';
            }
        },
