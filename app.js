        calculateTotals() {
            const subtotal = this.newInvoice.items.reduce((sum, item) => sum + ((Number(item.qty) || 0) * (Number(item.price) || 0)), 0);
            this.newInvoice.subtotal = subtotal;
            const tax = (subtotal * (Number(this.newInvoice.taxRate) || 0)) / 100;
            const shipping = Number(this.newInvoice.shippingFee) || 0;
            this.newInvoice.total = subtotal + tax + shipping;

            // Multiple payments calculation
            if (Array.isArray(this.newInvoice.payments) && this.newInvoice.payments.length > 0) {
                const totalFromPayments = this.newInvoice.payments.reduce((sum, p) => sum + (Number(p.amount) || 0), 0);
                this.newInvoice.amountPaid = totalFromPayments;
            } else {
                this.newInvoice.amountPaid = Number(this.newInvoice.amountPaid) || 0;
            }

            this.newInvoice.balance = this.newInvoice.total - this.newInvoice.amountPaid;
            
            if (this.newInvoice.balance <= 0 && this.newInvoice.total > 0) {
                this.newInvoice.status = 'Paid';
            } else if (this.newInvoice.amountPaid > 0 && this.newInvoice.balance > 0) {
                this.newInvoice.status = 'Partial';
            } else {
                this.newInvoice.status = 'Unpaid';
            }
        },
