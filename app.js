            const totalSales = this.reportTotalSales || 0;
            const totalPaid = this.reportTotalPaid || 0;
            const totalBalance = this.reportTotalBalance || 0;
            const collectionRate = totalSales > 0 ? Math.round((totalPaid / totalSales) * 100) : 0;

            const groupMap = {};
            const monthNames = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

            invoices.forEach(inv => {
                const dStr = (inv.date || '').slice(0, 10);
                let key = dStr;
                let label = dStr;

                if (this.reportPeriod === 'yearly' || this.reportPeriod === 'all') {
                    key = dStr.slice(0, 7) || 'Other';
                    if (key !== 'Other') {
                        const parts = key.split('-');
                        const mIdx = parseInt(parts[1], 10) - 1;
                        label = (monthNames[mIdx] || parts[1]) + (this.reportPeriod === 'all' ? ` '${parts[0].slice(2)}` : '');
                    }
                } else if (this.reportPeriod === 'daily') {
                    key = inv.invoiceNumber || inv.id;
                    label = inv.invoiceNumber || 'Inv';
                } else if (dStr) {
                    const parts = dStr.split('-');
                    const mIdx = parseInt(parts[1], 10) - 1;
                    label = `${parseInt(parts[2], 10)} ${monthNames[mIdx] || parts[1]}`;
                }

                if (!groupMap[key]) {
                    groupMap[key] = {
                        key,
                        label,
                        rawDate: dStr,
                        sales: 0,
                        paid: 0,
                        balance: 0,
                        count: 0
                    };
                }
                groupMap[key].sales += (Number(inv.total) || 0);
                groupMap[key].paid += (Number(inv.amountPaid) || 0);
                groupMap[key].balance += (Number(inv.balance) || 0);
                groupMap[key].count += 1;
            });

            const sorted = Object.values(groupMap).sort((a, b) => (a.rawDate || '').localeCompare(b.rawDate || ''));
            const displayBars = sorted.slice(-14);
            const maxVal = Math.max(...displayBars.map(g => g.sales), 1);

            const bars = displayBars.map(g => ({
                ...g,
                salesHeightPct: Math.max(12, Math.round((g.sales / maxVal) * 100)),
                paidHeightPct: Math.round((g.paid / maxVal) * 100),
                balanceHeightPct: Math.round((g.balance / maxVal) * 100)
            }));

