        async apiRequest(path, options = {}) {
            try {
                const url = `${API_URL}${path}`;
                let res = await fetch(url, options);
                if (res.ok) return res;

                // Fallback for live PHP hosts without rewrite rules
                if ((res.status === 404 || !res.ok) && path.startsWith('/api/')) {
                    const route = path.replace('/api/', '');
                    const fallbackUrl = `${API_URL}/api.php?route=${encodeURIComponent(route)}`;
                    const fallbackRes = await fetch(fallbackUrl, options);
                    if (fallbackRes.ok) return fallbackRes;
                }
                return res;
            } catch (err) {
                if (path.startsWith('/api/')) {
                    const route = path.replace('/api/', '');
                    try {
                        const fallbackUrl = `${API_URL}/api.php?route=${encodeURIComponent(route)}`;
                        return await fetch(fallbackUrl, options);
                    } catch (e) {}
                }
                throw err;
            }
        },
        async loadData() {
            // 1. Initial quick load from local cache
            this.loadFromLocalStorage();

            // 2. Fetch fresh real-time data from database
            try {
                const res = await this.apiRequest('/api/data');
                if (res && res.ok) {
                    const data = await res.json();
                    if (data.users && Array.isArray(data.users) && data.users.length > 0) {
                        this.users = data.users;
                        if (!this.users.some(u => (u.username || '').toLowerCase() === 'admin')) {
                            this.users.unshift({ id: 'usr_admin_001', username: 'admin', password: 'password', role: 'admin' });
                        }
                    }
                    if (data.settings) this.settings = { ...this.settings, ...data.settings };
                    if (data.products) this.products = data.products;
                    if (data.customers) this.customers = data.customers;
                    if (data.invoices) this.invoices = data.invoices;
                    if (data.history) this.history = data.history;
                    if (data.userSessions && Array.isArray(data.userSessions)) this.userSessions = data.userSessions;
                    this.dbConnected = true;
                    this.saveToLocalStorage();
                } else {
                    this.dbConnected = false;
                }
            } catch (e) {
                this.dbConnected = false;
            }

            // Restore user session ONLY from sessionStorage (automatically logs out when closed)
            const sessionId = sessionStorage.getItem('rp_session_id');
            if (sessionId) {
                const user = this.users.find(u => u.id === sessionId);
                if (user) {
                    this.currentUser = user;
                    this.isLoggedIn = true;
                    this.startSessionTracking(user);
                }
            }
            // Clear any lingering localStorage session for security
            try { localStorage.removeItem('rp_session_id'); } catch (e) {}
            
            this.applyTheme();
        },
