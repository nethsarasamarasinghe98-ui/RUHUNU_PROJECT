        preparePrintAutoFit() {
            const el = document.getElementById('print-area');
            if (!el) return;

            // Remove artificial screen min-height temporarily to measure true unconstrained content height
            const prevMinHeight = el.style.minHeight;
            el.style.minHeight = '0px';

            // Printable single-page height target in 96 DPI CSS pixels (conservative for both A4 & US Letter)
            const targetPageHeight = 980;
            const actualHeight = el.scrollHeight;

            // Restore screen minHeight
            el.style.minHeight = prevMinHeight;

            if (actualHeight > targetPageHeight && this.settings.autoFitOnePage !== false) {
                const zoom = Math.max(0.60, Math.min(1, targetPageHeight / actualHeight));
                el.style.setProperty('--inv-print-zoom', zoom.toFixed(3));
            } else {
                el.style.setProperty('--inv-print-zoom', '1');
            }
        },
