-- ----------------------------------------------------------------------------
-- 1. USERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(50) PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_username ON users (username);

-- ----------------------------------------------------------------------------
-- 2. SETTINGS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS settings (
    id INT PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL DEFAULT 'RUHUNU PRODUCTS',
    sidebar_subtitle VARCHAR(255) DEFAULT 'Billing Suite',
    logo TEXT,
    logo_animated BOOLEAN DEFAULT TRUE,
    address_line1 VARCHAR(255) DEFAULT 'Main Street, Matara',
    address_line2 VARCHAR(255) DEFAULT 'Southern Province, Sri Lanka',
    phone VARCHAR(50) DEFAULT '',
    mobile_number VARCHAR(50) DEFAULT '+94 41 222 3333',
    whatsapp_number VARCHAR(50) DEFAULT '+94 71 234 5678',
    email VARCHAR(100) DEFAULT 'info@ruhunupurchases.com',
    footer_note TEXT DEFAULT 'Thank you for your business!',
    terms_info TEXT DEFAULT 'Please make cheques payable to Ruhunu Products.',
    bank_name VARCHAR(100) DEFAULT 'Bank of Ceylon (BOC)',
    account_name VARCHAR(100) DEFAULT 'Ruhunu Products',
    account_number VARCHAR(50) DEFAULT '0012345678',
    branch_name VARCHAR(100) DEFAULT 'Matara City Branch',
    bank_details_position VARCHAR(20) DEFAULT 'left' CHECK (bank_details_position IN ('left', 'center', 'right')),
    theme VARCHAR(20) DEFAULT 'light' CHECK (theme IN ('light', 'dark')),
    header_color VARCHAR(20) DEFAULT '#16a34a',
    logo_size INT DEFAULT 60,
    watermark_image TEXT,
    watermark_size INT DEFAULT 50,
    watermark_opacity INT DEFAULT 10,
    logo_position VARCHAR(20) DEFAULT 'left' CHECK (logo_position IN ('left', 'right', 'top')),
    company_details_alignment VARCHAR(20) DEFAULT 'left' CHECK (company_details_alignment IN ('left', 'center', 'right')),
    empty_rows_count INT DEFAULT 4,
    margin_top INT DEFAULT 0,
    margin_right INT DEFAULT 20,
    margin_bottom INT DEFAULT 20,
    margin_left INT DEFAULT 20,
    invoice_numbering_mode VARCHAR(20) DEFAULT 'auto' CHECK (invoice_numbering_mode IN ('auto', 'manual')),
    auto_start_number INT DEFAULT 1,
    notifications_enabled BOOLEAN DEFAULT TRUE,
    seal_enabled BOOLEAN DEFAULT TRUE,
    seal_image TEXT DEFAULT 'paid_stamp.png',
    seal_position VARCHAR(50) DEFAULT 'top-right',
    seal_top INT DEFAULT 16,
    seal_left INT DEFAULT 72,
    seal_rotation INT DEFAULT -15,
    seal_size INT DEFAULT 150,
    seal_opacity INT DEFAULT 88,
    auto_fit_one_page BOOLEAN DEFAULT TRUE,
    hide_bank_when_payments BOOLEAN DEFAULT FALSE,
    bottom_stamp_text TEXT DEFAULT 'Generated by {companyName}',
    footer_horizontal_align VARCHAR(50) DEFAULT 'space-between',
    footer_vertical_offset INT DEFAULT 0,
    footer_horizontal_offset INT DEFAULT 0,
    footer_show_divider BOOLEAN DEFAULT TRUE,
    footer_show_invoice_number BOOLEAN DEFAULT TRUE,
    footer_font_size INT DEFAULT 11,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 3. CUSTOMERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS customers (
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(50),
    email VARCHAR(100),
    address_line1 VARCHAR(255),
    address_line2 VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_customers_name ON customers (name);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers (phone);

-- ----------------------------------------------------------------------------
-- 4. PRODUCTS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
    id VARCHAR(50) PRIMARY KEY,
    code VARCHAR(50),
    name VARCHAR(255) NOT NULL,
    brand VARCHAR(100) DEFAULT '',
    price NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_products_code ON products (code);
CREATE INDEX IF NOT EXISTS idx_products_brand ON products (brand);

-- ----------------------------------------------------------------------------
-- 5. INVOICES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invoices (
    id VARCHAR(50) PRIMARY KEY,
    invoice_number VARCHAR(50) NOT NULL UNIQUE,
    customer_id VARCHAR(50) REFERENCES customers(id) ON DELETE SET NULL ON UPDATE CASCADE,
    date VARCHAR(50) NOT NULL,
    shipping_fee NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    hide_bank_details BOOLEAN NOT NULL DEFAULT FALSE,
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    tax_rate NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    total NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    amount_paid NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    balance NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'Unpaid' CHECK (status IN ('Paid', 'Partial', 'Unpaid')),
    manual_invoice_number VARCHAR(50) DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_invoices_invoice_number ON invoices (invoice_number);
CREATE INDEX IF NOT EXISTS idx_invoices_customer_id ON invoices (customer_id);
CREATE INDEX IF NOT EXISTS idx_invoices_date ON invoices (date);
CREATE INDEX IF NOT EXISTS idx_invoices_status ON invoices (status);

-- ----------------------------------------------------------------------------
-- 6. INVOICE ITEMS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invoice_items (
    id SERIAL PRIMARY KEY,
    invoice_id VARCHAR(50) NOT NULL REFERENCES invoices(id) ON DELETE CASCADE ON UPDATE CASCADE,
    product_id VARCHAR(50) REFERENCES products(id) ON DELETE SET NULL ON UPDATE CASCADE,
    description TEXT NOT NULL,
    brand VARCHAR(100) DEFAULT '',
    show_brand BOOLEAN NOT NULL DEFAULT FALSE,
    qty NUMERIC(12, 2) NOT NULL DEFAULT 1.00,
    price NUMERIC(12, 2) NOT NULL DEFAULT 0.00
);

CREATE INDEX IF NOT EXISTS idx_invoice_items_invoice_id ON invoice_items (invoice_id);

-- ----------------------------------------------------------------------------
-- 7. INVOICE PAYMENTS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invoice_payments (
    id VARCHAR(50) PRIMARY KEY,
    invoice_id VARCHAR(50) NOT NULL REFERENCES invoices(id) ON DELETE CASCADE ON UPDATE CASCADE,
    amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    date VARCHAR(50) NOT NULL,
    method VARCHAR(50) DEFAULT 'Cash',
    note TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_invoice_payments_invoice_id ON invoice_payments (invoice_id);

-- ----------------------------------------------------------------------------
-- 8. ACTIVITY HISTORY TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity_history (
    id VARCHAR(50) PRIMARY KEY,
    action VARCHAR(100) NOT NULL,
    details TEXT,
    "user" VARCHAR(100) NOT NULL DEFAULT 'System',
    date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_activity_history_date ON activity_history (date);

-- ----------------------------------------------------------------------------
-- 9. USER SESSIONS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_sessions (
    id VARCHAR(50) PRIMARY KEY,
    user_id VARCHAR(50),
    username VARCHAR(100) NOT NULL,
    login_time TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    logout_time TIMESTAMP WITH TIME ZONE,
    duration_seconds INT DEFAULT 0,
    is_online BOOLEAN DEFAULT TRUE,
    device VARCHAR(100) DEFAULT 'Desktop'
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_user_id ON user_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_user_sessions_login_time ON user_sessions (login_time);

